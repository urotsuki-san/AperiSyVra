use aperisyvra_core::{decapsulate, encapsulate, keypair_from_seed};
use rand::rngs::StdRng;
use rand::SeedableRng;

#[test]
fn second_threshold_pass_recovers_the_known_difficult_sequence() {
    let secret_seed = [
        0x78, 0xf8, 0x94, 0xfe, 0x72, 0xf3, 0x6e, 0x3c, 0xc6, 0x13, 0x83, 0x4f, 0xe9, 0x2f, 0x37,
        0xef, 0x36, 0x53, 0x6d, 0x23, 0xba, 0xef, 0x3e, 0x96, 0x97, 0x9b, 0x77, 0xe3, 0x6d, 0xc1,
        0xa7, 0xf4,
    ];
    let random_seed = [
        0xaa, 0xef, 0xc6, 0x93, 0x83, 0x4f, 0xe9, 0x2f, 0xfe, 0x72, 0xf3, 0x6e, 0x3c, 0x31, 0xf8,
        0x94, 0xfb, 0xee, 0x63, 0x69, 0x33, 0xd5, 0x36, 0xa2, 0x16, 0x7c, 0x4a, 0x7f, 0xb9, 0x79,
        0x37, 0xde,
    ];

    let (public_key, secret_key) = keypair_from_seed(secret_seed).expect("keypair");
    let mut rng = StdRng::from_seed(random_seed);

    for trial in 0..=26 {
        let (ciphertext, expected) = encapsulate(&public_key, &mut rng);
        let recovered = decapsulate(&secret_key, &ciphertext).expect("decapsulate");
        assert_eq!(expected, recovered, "decoder mismatch at trial {trial}");
    }
}
